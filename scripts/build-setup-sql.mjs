// Concatenates supabase/migrations/*.sql into supabase/setup.sql, a single file
// that can be pasted into the Supabase SQL editor for a fresh project.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const header = `-- =============================================================================
-- VALORANT Team Hub: complete database setup for a NEW Supabase project.
-- Generated from supabase/migrations by \`npm run db:bundle\`. Do not edit by hand.
-- Paste everything into Supabase → SQL Editor → New query, then press Run.
-- =============================================================================
`;
const body = files.map((f) => `\n-- >>> ${f}\n${readFileSync(join(dir, f), "utf8").trim()}\n`).join("");
// The app applies pending migrations itself on start-up (src/lib/migrate.ts);
// it reads them from this generated module so they ship inside the server bundle.
const generated = `// Generated by scripts/build-setup-sql.mjs from supabase/migrations. Do not edit.
export const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(
  files.map((f) => ({ name: f.replace(/\.sql$/, ""), sql: readFileSync(join(dir, f), "utf8") })),
  null,
  2,
)};
`;
writeFileSync("src/lib/migrations.generated.ts", generated);

const tracking = `
-- >>> Record the migrations above as applied, so the app only runs newer ones.
create table if not exists app.schema_migrations (name text primary key, applied_at timestamptz not null default now());
insert into app.schema_migrations (name) values
${files.map((f) => `  ('${f.replace(/\.sql$/, "")}')`).join(",\n")}
on conflict (name) do nothing;
`;

const footer = `
-- >>> First owner: the result of this line is a one-time invitation code.
-- Open <your site>/join, enter it with your email and a password, and you are the owner.
select app.create_owner_invitation() as owner_invitation_code;
`;
writeFileSync("supabase/setup.sql", header + body + tracking + footer);
console.log(`supabase/setup.sql written from ${files.length} migrations`);
